export const TRANSLATIONS: Record<Language, Dictionary> = { en, fr };

/**
 * Returns the text associated with a key (e.g. 'nav.home'), replacing the
 * {name} parameters. An unknown key is returned as is.
 */
export function translate(
  dictionary: Dictionary,
  key: string,
  params?: Record<string, string | number>,
): string {
  let value: string | Dictionary | undefined = dictionary;
  for (const part of key.split('.')) {
    value = typeof value === 'object' ? value[part] : undefined;
  }
  if (typeof value !== 'string') return key;
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (text, name: string) =>
    name in params ? String(params[name]) : text,
  );
}

/** Tells whether a value is a supported language. */
export function isLanguage(value: unknown): value is Language {
  return value === 'en' || value === 'fr';
}
