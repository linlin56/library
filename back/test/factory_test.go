// ===================== Abstract polymorphism =====================

func TestFactory_AbstractPolymorphism(t *testing.T) {
	author := models.NewAuthor(1, "Hugo", "Victor")
	factories := []factory.ItemFactory{
		&factory.BookFactory{
			Title:   "Notre-Dame de Paris",
			Deposit: 2.0,
			Isbn:    "978-0140443530",
			Author:  author,
		},
		&factory.JournalFactory{
			Title:           "Science et Vie",
			Deposit:         1.0,
			IssueNumber:     5,
			PublicationDate: time.Now(),
		},
	}
	for i, f := range factories {
		item := f.CreateItem()
		if item.GetTitle() == "" {
			t.Errorf("factory[%d]: GetTitle must not be empty", i)
		}
		if item.GetDeposit() <= 0 {
			t.Errorf("factory[%d]: GetDeposit must be positive, got %.2f", i, item.GetDeposit())
		}
	}
}
